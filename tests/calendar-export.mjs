import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';

const source=readFileSync(new URL('../calendar-export.js',import.meta.url),'utf8');
const sandbox={};
vm.runInNewContext(source,{window:sandbox,Date,console,setTimeout},{filename:'calendar-export.js'});
const build=sandbox.CPPlannerCalendar.build;
const base=Array.from({length:33},(_,i)=>({name:'Refeição '+i,method:'pan'}));
base[5]={name:'Assado de novilho',method:'braise'};
base[32]={name:'Lagartos, especiais; no forno',method:'roast'};
const original=JSON.stringify(base);
const now=new Date('2026-11-01T09:00:00Z');
const file=build({start:'2026-11-01',hour:'19:30',meals:base,manualMeals:{0:32},guideTime:()=>[180,300],createdAt:now});
const unfolded=file.replace(/\r\n /g,'');
const events=[...unfolded.matchAll(/BEGIN:VEVENT\r\n([\s\S]*?)END:VEVENT/g)].map(x=>x[1]);
const dinners=events.filter(x=>x.includes('UID:jantar-'));
const slow=events.filter(x=>x.includes('UID:preparar-'));
const shops=events.filter(x=>x.includes('UID:compras-'));
assert.equal(dinners.length,30);
assert.equal(slow.length,2,'Only slow selected dishes should receive preparation events');
assert.equal(shops.length,5);
assert.match(dinners[0],/DTSTART:20261101T193000/);
assert.match(dinners[0],/DTEND:20261101T203000/);
assert.match(dinners[0],/SUMMARY:Jantar: Lagartos\\, especiais\\; no forno/);
assert.match(slow[0],/DTSTART:20261101T140000/,'Slow cooking must start 5h30 before dinner');
assert.match(shops[0],/DTSTART:20261031T100000/,'First shopping should be Saturday before plan');
assert.match(shops[4],/DTSTART:20261128T100000/,'Final partial week has its own shopping event');
assert.equal(JSON.stringify(base),original,'Export must not mutate recipes');
assert.equal(file.split('BEGIN:VCALENDAR').length,2);
assert.ok(file.endsWith('END:VCALENDAR\r\n'));
const second=build({start:'2026-11-01',hour:'21:15',meals:base,manualMeals:{0:32},guideTime:()=>[180,300],createdAt:now});
assert.match(second,/DTSTART:20261101T211500/);
assert.match(second,/DTEND:20261101T221500/);
const dates=[...second.matchAll(/DTSTART:(\d{8}T\d{6})/g)].map(x=>x[1]);
assert.ok(dates.every(x=>/^\d{8}T\d{6}$/.test(x)),'Timestamps should use local calendar syntax');
const long=base.map((x,i)=>i===0?{name:'Ó'.repeat(80)+',;\\',method:'pan'}:x);
const folded=build({start:'2026-11-01',hour:'19:00',meals:long,createdAt:now});
assert.match(folded,/\r\n /,'Long UTF-8 lines must be folded');
assert.throws(()=>build({start:'2026-02-30',hour:'19:00',meals:base}),/Data de início inválida/);
assert.throws(()=>build({start:'2026-11-01',hour:'25:00',meals:base}),/Hora da refeição inválida/);
console.log('PASS: 30 selected meals, 5 shopping reminders, slow prep, edited hours, UTF-8 folding and safe export');

const quickRoast=build({start:'2026-11-01',hour:'19:30',meals:base,manualMeals:{0:32},guideTime:(m,i)=>i===32?[25,40]:[180,300],createdAt:now});
assert.ok(!quickRoast.includes('UID:preparar-20261101'),'40-minute oven dish must not create a four-hour prep reminder');
console.log('PASS: quick oven recipes do not receive slow-cooking reminders');
