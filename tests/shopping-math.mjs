import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';

const context={window:{}};
vm.runInNewContext(fs.readFileSync('shopping-math.js','utf8'),context,{filename:'shopping-math.js'});
const m=context.window.CPShoppingMath;
assert.ok(m&&typeof m.weekProjection==='function');
const meals=Array.from({length:30},()=>({items:{}}));
meals[0]={items:{entrecote:150,ovos:2}};
meals[1]={items:{entrecote:120,ovos:3}};
meals[7]={items:{entrecote:200,ovos:1}};
meals[8]={items:{entrecote:100}};
meals[14]={items:{entrecote:140}};
meals[28]={items:{salmao:400,ovos:1}};
meals[29]={items:{salmao:200}};
const fixtures={meals,stock:{entrecote:300,ovos:4,salmao:500},prices:{entrecote:20,ovos:0.3,salmao:20},asOfWeek:0};
const row=(o,key)=>o.rows.find(x=>x.key===key);
let a=m.weekProjection({...fixtures,week:0});
assert.equal(row(a,'entrecote').required,270);
assert.equal(row(a,'entrecote').covered,270);
assert.equal(row(a,'entrecote').toBuy,0);
assert.equal(row(a,'ovos').required,5);
assert.equal(row(a,'ovos').toBuy,1);
assert.ok(Math.abs(a.netCost-0.3)<0.001);
let b=m.weekProjection({...fixtures,week:1});
assert.equal(row(b,'entrecote').covered,30,'Stock should only be counted once across weeks');
assert.equal(row(b,'entrecote').toBuy,270);
assert.equal(row(b,'ovos').covered,0);
let c=m.weekProjection({...fixtures,week:2});
assert.equal(row(c,'entrecote').covered,0,'Previous weeks must reserve the stock first');
let last=m.weekProjection({...fixtures,week:4});
assert.equal(row(last,'salmao').covered,500);
assert.equal(row(last,'salmao').toBuy,100);
assert.equal(last.rows.length,2,'Last week must be only 2 days');
const swapped=m.weekProjection({...fixtures,week:0,selected:{0:7}});
assert.equal(row(swapped,'entrecote').required,320,'Meal substitution ignored');
assert.equal(row(swapped,'ovos').required,4,'Meal substitution ignored');
const historical=m.weekProjection({...fixtures,week:0,asOfWeek:2});
assert.equal(row(historical,'entrecote').covered,0,'Should not apply current inventory retroactively');
assert.equal(historical.isPast,true);
assert.equal(m.weekFromIndex(0),0);
assert.equal(m.weekFromIndex(29),4);
const zero=m.weekProjection({...fixtures,week:0,stock:{},prices:{}});
assert.equal(row(zero,'entrecote').toBuy,270);
assert.equal(zero.grossCost,0);
assert.equal(zero.netCost,0);
console.log('PASS: stock allocation, weekly demand, replacements, egg units, future weeks and pricing');
